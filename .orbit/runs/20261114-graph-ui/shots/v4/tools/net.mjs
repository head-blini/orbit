import { connect } from './c.mjs';
const list = await (await fetch('http://127.0.0.1:9333/json')).json();
const t = list.find(x => x.type === 'page' && x.url.includes('1420'));
const ws = new WebSocket(t.webSocketDebuggerUrl);
await new Promise(r => ws.onopen = r);
const reqs = new Set(); const fails = [];
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.method === 'Network.requestWillBeSent') reqs.add(m.params.request.url.replace(/[?#].*/, '').replace(/%5C/gi, '/')); if (m.method === 'Network.loadingFailed') fails.push(m.params.errorText + ' ' + (m.params.blockedReason || '')); };
ws.send(JSON.stringify({ id: 1, method: 'Network.enable' }));
ws.send(JSON.stringify({ id: 2, method: 'Network.setCacheDisabled', params: { cacheDisabled: true } }));
const c = await connect(9333, '1420');
await c.send('Page.reload', { ignoreCache: true });
await new Promise(r => setTimeout(r, 6000));
const hosts = new Set([...reqs].map(u => { try { return new URL(u).origin; } catch { return u; } }));
console.log('origins', JSON.stringify([...hosts]));
console.log('font request', JSON.stringify([...reqs].filter(u => /woff2?$/.test(u))));
console.log('non-local requests', JSON.stringify([...reqs].filter(u => !/^(http:\/\/(localhost:1420|ipc\.localhost|asset\.localhost)|ws:\/\/localhost:1420|data:|blob:)/.test(u))));
console.log('loadingFailed', JSON.stringify(fails));
console.log('fonts', await c.ev(`JSON.stringify([...document.fonts].map(f=>[f.family,f.status]))`));
console.log('console errors? CSP violations via securitypolicyviolation not captured; see below');
c.close(); ws.close();
