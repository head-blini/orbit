import { connect, MEASURE } from './c.mjs';
import fs from 'node:fs';
const S = 'C:/Users/lclk1/Projects/orbit/.orbit/runs/20261114-graph-ui/shots/v2/';
const c = await connect(9333, '1420');
await c.view(+(process.env.VW || 1400), +(process.env.VH || 900));
const sleep = ms => new Promise(r => setTimeout(r, ms));
const { SESS, NODE, PRE, OUT, KEEPFOCUS } = process.env;
if (SESS) console.log('sess', await c.ev(`(() => { const b=[...document.querySelectorAll('.sess')].find(e=>e.querySelector('.name').textContent.trim()===${JSON.stringify(SESS)}); if(!b) return 'none'; b.click(); return 'ok'; })()`));
await sleep(600);
if (NODE) console.log('node', await c.ev(`(() => { const b=[...document.querySelectorAll('.graph button')].find(e=>e.innerText.includes(${JSON.stringify(NODE)})); if(!b) return 'none'; b.click(); return 'ok'; })()`));
await sleep(500);
if (PRE) console.log('pre', await c.ev(PRE));
if (!KEEPFOCUS) await c.ev(`document.activeElement && document.activeElement.blur()`);
await sleep(500);
await c.shot(S + OUT + '.png');
const m = JSON.parse(await c.ev(MEASURE));
const info = await c.ev(`JSON.stringify({vp:[innerWidth,innerHeight], docScroll:[document.documentElement.scrollWidth,document.documentElement.scrollHeight,scrollY], graph:(g=>g&&[g.scrollWidth,g.clientWidth,g.scrollHeight,g.clientHeight,g.scrollTop])(document.querySelector('.graph')), sessions:(g=>g&&[g.scrollHeight,g.clientHeight,g.scrollTop])(document.querySelector('.sessions')), detail:(g=>g&&[g.scrollHeight,g.clientHeight,g.scrollTop])(document.querySelector('.detail')), chat:(g=>g&&[g.scrollHeight,g.clientHeight])(document.querySelector('.chat'))})`);
fs.writeFileSync(S + OUT + '-measure.json', JSON.stringify({ info: JSON.parse(info), m }, null, 1));
console.log(OUT, info, 'nodes', m.nodes.length, JSON.stringify(m.nodes.map(n => [n.cls, n.li && n.li.w, n.li && n.li.h])));
c.close();
